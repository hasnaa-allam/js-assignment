var copyOfArray = recipes.slice();
var recipesRandom;

function displayRecipes(){

    if(copyOfArray.length === 0){
       copyOfArray = recipes.slice();
    }

    recipesRandom = Math.floor(Math.random() * copyOfArray.length);
    recipeImage.src = copyOfArray[recipesRandom].image;
    recipeAverage.innerHTML = copyOfArray[recipesRandom].rating;
    recipeQuantity.innerHTML = copyOfArray[recipesRandom].reviewQuantity;
    recipeDifficulty.innerHTML = copyOfArray[recipesRandom].difficulty;
    recipeCategory.innerHTML = copyOfArray[recipesRandom].category;
    recipeName.innerHTML = copyOfArray[recipesRandom].title;
    recipeDescription.innerHTML = copyOfArray[recipesRandom].description;
    prepTime.innerHTML = copyOfArray[recipesRandom].PrepTime;
    cookTime.innerHTML = copyOfArray[recipesRandom].CookTime;
    serving.innerHTML = copyOfArray[recipesRandom].Servings;

    // Nutrition
    caloriesText.innerHTML = copyOfArray[recipesRandom].nutrition.Calories;
    carbsText.innerHTML = copyOfArray[recipesRandom].nutrition.Carbs;
    fatText.innerHTML = copyOfArray[recipesRandom].nutrition.Fat;
    proteinText.innerHTML = copyOfArray[recipesRandom].nutrition.Protein;
    fiberText.innerHTML = copyOfArray[recipesRandom].nutrition.Fiber;
    sodiumText.innerHTML = copyOfArray[recipesRandom].nutrition.Sodium;

    // Ingredients
    displayIngredients();
    // Instructions
    displayInstructions();
    // Tips
    displayTips();

    copyOfArray.splice(recipesRandom, 1);
}

function displayIngredients(){
    var ingredientsArray = copyOfArray[recipesRandom].ingredients;
    var cartona = "";
    for(var i = 0; i < ingredientsArray.length; i++){
        cartona += `
          <li class="d-flex align-items-start gap-3 mb-3">
            <div class="ingredient-number d-flex align-items-center justify-content-center text-heading text-white">
              ${i + 1}
            </div>
            <span class="ingredient-name">${ingredientsArray[i]}</span>
          </li>`;
    }
    ingredientList.innerHTML = cartona;
}

function displayInstructions(){
    var instructionsArray = copyOfArray[recipesRandom].instructions;
    var cartona = "";
    for(var i = 0; i < instructionsArray.length; i++){
        cartona += `
            <li class="d-flex align-items-center gap-3 mb-5">
                <div class="instructions-number fs-4 d-flex align-items-center justify-content-center text-heading text-white">
                    ${i + 1}
                </div>
                <span class="instructions-name mb-0">
                    ${instructionsArray[i]}
                </span>
            </li> 
           `;
    }
    instructionsList.innerHTML = cartona;
}

function displayTips(){
    var tipsArray = copyOfArray[recipesRandom].tips;
    var cartona = "";
    for(var i = 0; i < tipsArray.length; i++){
        cartona += `
            <div class="d-flex align-items-center mb-3 gap-3 p-3 rounded-4 chefs-card">
                <i class="fa-solid fa-circle-check fs-4" style="color: #e17100"></i>
                    <p class="chefs-name">
                      ${tipsArray[i]}  
                    </p>
            </div>        
        `;
    }
    chefsList.innerHTML = cartona;
}